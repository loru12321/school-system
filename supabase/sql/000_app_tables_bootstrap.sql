create index if not exists idx_issues_status_created
on public.issues(status, created_at desc);

create index if not exists idx_issues_school_class_status
on public.issues(school, student_class, status, created_at desc);

alter table public.issues enable row level security;
revoke all on public.issues from anon, authenticated;
comment on table public.issues is 'Legacy Supabase table. Production uses authenticated Worker routes; browser direct access disabled by RLS.';

