create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create table if not exists public.system_data (
  key text primary key,
  content text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_system_data_updated_at
on public.system_data(updated_at desc);

create index if not exists idx_system_data_key_prefix_updated
on public.system_data(key text_pattern_ops, updated_at desc);

drop trigger if exists trg_system_data_updated_at on public.system_data;

create trigger trg_system_data_updated_at
before update on public.system_data
for each row execute function public.set_updated_at();

alter table public.system_data enable row level security;
revoke all on public.system_data from anon, authenticated;
comment on table public.system_data is 'Legacy Supabase table. Production uses Cloudflare D1/Worker routes; browser direct access disabled by RLS.';

create table if not exists public.issues (
  id bigint primary key generated by default as identity,
  student_name text not null default '',
