const assert = require('assert');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const main = fs.readFileSync(path.join(root, 'desktop/main.cjs'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'desktop/preload.cjs'), 'utf8');
const offline = fs.readFileSync(path.join(root, 'desktop/offline.html'), 'utf8');
const builder = fs.readFileSync(path.join(root, 'electron-builder.yml'), 'utf8');
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

assert.ok(main.includes('requestSingleInstanceLock'), 'desktop shell must enforce one running instance');
assert.ok(main.includes('contextIsolation: true'), 'renderer must use context isolation');
assert.ok(main.includes('nodeIntegration: false'), 'renderer must not expose Node.js');
assert.ok(main.includes('sandbox: true'), 'renderer must use the Chromium sandbox');
assert.ok(main.includes('https://schoolsystem.com.cn'), 'desktop shell must use the production origin');
assert.ok(main.includes('LOCAL_APP_ENTRY'), 'desktop shell should keep the bundled app path available for package contract checks');
assert.ok(main.includes("loadURL(PRODUCTION_URL)"), 'desktop shell must load the production origin before any local fallback');
assert.ok(!main.includes("loadFile(LOCAL_APP_ENTRY)"), 'desktop shell must not use the bundled local app as the default login surface');
assert.ok(main.includes('setWindowOpenHandler'), 'new windows must be intercepted');
assert.ok(main.includes('will-navigate'), 'top-level navigation must be allowlisted');
assert.ok(main.includes('shell.openExternal'), 'approved release links should open outside the app');
assert.ok(main.includes("url.username === ''") && main.includes("url.password === ''"), 'allowlisted URLs must reject embedded credentials');
assert.ok(main.includes('url.pathname === RELEASE_PATH_PREFIX'), 'release allowlist must use an exact path boundary');
assert.ok(main.includes('offline.html'), 'failed initial loads must show the offline fallback');
assert.ok(main.includes('new Tray'), 'desktop shell should expose a Windows tray entry');
assert.ok(main.includes('setLoginItemSettings'), 'desktop shell should manage launch-at-login from the tray');
assert.ok(main.includes("closeBehavior: 'quit'"), 'clicking the close button should quit by default');
assert.ok(main.includes("mainWindow.on('close'") && main.includes('mainWindow.destroy()') && main.includes('app.exit(0)'), 'native close button must force the desktop app to exit');
assert.ok(main.includes("webContents.on('will-prevent-unload'"), 'desktop close should not be blocked by page beforeunload handlers');
assert.ok(main.includes('setImmediate(showMainWindow)'), 'tray menu actions should be dispatched from the main process');
assert.ok(main.includes('desktopWarmup'), 'desktop shell should prewarm production cloud connections');
assert.ok(main.includes('safeStorage') && main.includes('LOGIN_PROFILE_FILE'), 'desktop shell should persist login autofill data through protected local storage');
assert.ok(main.includes('DESKTOP_IPC_HANDLERS'), 'desktop IPC must be centralized behind an allowlist');
assert.ok(preload.includes('contextBridge.exposeInMainWorld'), 'preload should expose a narrow metadata bridge');
assert.ok(preload.includes('Object.freeze'), 'exposed metadata must be immutable');
assert.ok(preload.includes('allowedInvocations'), 'preload IPC must be limited to approved desktop channels');
assert.ok(preload.includes('desktop:getSettings') && preload.includes('desktop:updateSettings'), 'preload should expose desktop settings only through approved channels');
assert.ok(preload.includes('desktop:saveLoginProfile') && preload.includes('desktop:clearLoginProfile'), 'preload should expose only approved login autofill channels');
assert.ok(!preload.includes('ipcRenderer.send'), 'preload must not expose fire-and-forget IPC');
assert.ok(main.includes('additionalArguments'), 'sandboxed preload metadata should arrive through launch arguments');
assert.ok(!preload.includes("require('../package.json')"), 'sandboxed preload must not require local files');
assert.ok(offline.includes('Content-Security-Policy'), 'offline page should declare a CSP');
assert.ok(builder.includes('school-system-windows-${version}-${arch}.${ext}'), 'installer artifact should carry version and architecture');
assert.ok(builder.includes('extraResources:'), 'Electron Builder must bundle local app resources');
assert.ok(builder.includes('from: dist'), 'Electron Builder must package the production dist app locally');
assert.ok(builder.includes('to: app'), 'Electron Builder must install local resources under resources/app');
assert.ok(builder.includes('icon: desktop/assets/icon.ico'), 'Electron Builder must apply the branded icon to the Windows executable');
assert.ok(builder.includes('installerIcon: desktop/assets/icon.ico'), 'NSIS installer must use the branded icon');
assert.ok(builder.includes('uninstallerIcon: desktop/assets/icon.ico'), 'NSIS uninstaller must use the branded icon');
assert.equal(packageJson.main, 'desktop/main.cjs', 'Electron must package the secure desktop entry point');
assert.equal(packageJson.scripts?.['desktop:start'], 'electron desktop/main.cjs');
assert.equal(packageJson.scripts?.['desktop:build'], 'electron-builder --config electron-builder.yml --win nsis --x64');
assert.equal(packageJson.build?.win?.icon, 'desktop/assets/icon.ico', 'Electron Builder must package the branded Windows icon');

console.log('desktop package contract tests passed');
