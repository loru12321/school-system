const assert = require('assert');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const budgets = {
    'public/assets/vendor/xlsx/xlsx.full.min.js': 900_000,
    'public/assets/vendor/alasql/alasql.min.js': 525_000,
    'public/assets/vendor/jspdf/jspdf.umd.min.js': 380_000,
    'public/assets/vendor/html2canvas/html2canvas.min.js': 210_000,
    'public/assets/vendor/chart.js/chart.umd.min.js': 215_000,
    'public/assets/vendor/sweetalert2/sweetalert2.all.min.js': 90_000,
    'public/assets/vendor/tabler-icons/tabler-icons.min.css': 22_000,
    'public/assets/vendor/tabler-icons/fonts/tabler-icons.woff2': 60_000
};

for (const [relativePath, maxBytes] of Object.entries(budgets)) {
    const filePath = path.join(root, relativePath);
    assert.ok(fs.existsSync(filePath), `${relativePath} should exist`);
    const size = fs.statSync(filePath).size;
    assert.ok(size <= maxBytes, `${relativePath} is ${size} bytes, above ${maxBytes}`);
}

const bootRuntime = fs.readFileSync(path.join(root, 'public/assets/js/boot-runtime.js'), 'utf8');
const runtimeLoaderRuntime = fs.readFileSync(path.join(root, 'public/assets/js/runtime-loader-runtime.js'), 'utf8');
const runtimeSurface = `${bootRuntime}\n${runtimeLoaderRuntime}`;
const sourceHtml = fs.readFileSync(path.join(root, 'src/index.html'), 'utf8');
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const tablerCss = fs.readFileSync(path.join(root, 'public/assets/vendor/tabler-icons/tabler-icons.min.css'), 'utf8');
const tablerSourceCss = fs.readFileSync(path.join(root, 'scripts/vendor/tabler-icons-full.css'), 'utf8');
assert.ok(runtimeLoaderRuntime.includes('ensureXlsxVendorLoaded'), 'XLSX should stay behind the lazy loader');
assert.ok(runtimeLoaderRuntime.includes('ensureAlasqlVendorLoaded'), 'AlaSQL should stay behind the lazy loader');
const bootVendorBlock = (bootRuntime.match(/BOOT_VENDOR_MODULES\s*=\s*\[([\s\S]*?)\];/) || [])[1] || '';
assert.ok(!bootVendorBlock.includes('xlsx.full.min.js'), 'XLSX must not be a boot vendor');
[
    'xlsx/xlsx.full.min.js',
    'alasql/alasql.min.js',
    'jspdf/jspdf.umd.min.js',
    'html2canvas/html2canvas.min.js',
    'chart.js/chart.umd.min.js'
].forEach((vendorPath) => {
    assert.ok(!sourceHtml.includes(`src="./assets/vendor/${vendorPath}"`), `${vendorPath} must not be a first-screen script`);
});
const shellPolishFactoryWarmup = (runtimeSurface.match(/'shell-polish':\s*bootSkill\(\s*['"][^'"]+['"]\s*,\s*['"]([^'"]+)['"]/) || [])[1] || '';
const shellPolishSkill = (runtimeSurface.match(/'shell-polish':\s*\{([\s\S]*?)\n\s*\}/) || [])[1] || '';
assert.ok(
  shellPolishFactoryWarmup === 'demand'
    || shellPolishSkill.includes("warmup: 'demand'")
    || shellPolishSkill.includes('warmup: "demand"'),
  'shell polish should load on demand, not during default desktop warmup'
);
assert.ok(packageJson.scripts['assets:tabler-icons'] === 'node scripts/build/subset-tabler-icons.mjs', 'Tabler icon subset generator should be exposed');
assert.ok(packageJson.scripts.build.includes('node scripts/build/subset-tabler-icons.mjs'), 'production build should regenerate the Tabler icon subset');
assert.ok(tablerCss.includes('Subset generated by scripts/build/subset-tabler-icons.mjs'), 'Tabler CSS should be generated from the subset script');
assert.ok(tablerCss.includes('format("woff2")'), 'Tabler subset should only publish modern woff2 fonts');
assert.ok(!tablerCss.includes('format("woff")'), 'Tabler subset should not reference legacy woff fonts');
assert.ok(!tablerCss.includes('format("truetype")'), 'Tabler subset should not reference legacy ttf fonts');
assert.ok(fs.existsSync(path.join(root, 'scripts/vendor/tabler-icons-full.woff2')), 'full Tabler source font should be retained outside public assets');
assert.ok(tablerSourceCss.includes('.ti-user-circle:before'), 'full Tabler CSS source should be retained for future subset regeneration');
assert.ok(!fs.existsSync(path.join(root, 'public/assets/vendor/tabler-icons/fonts/tabler-icons.woff')), 'legacy Tabler woff should not be shipped');
assert.ok(!fs.existsSync(path.join(root, 'public/assets/vendor/tabler-icons/fonts/tabler-icons.ttf')), 'legacy Tabler ttf should not be shipped');

console.log('vendor budget tests passed');
