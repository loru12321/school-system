import { spawnSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '../..');

const sourceCssPath = path.join(root, 'scripts', 'vendor', 'tabler-icons-full.css');
const sourceFontPath = path.join(root, 'scripts', 'vendor', 'tabler-icons-full.woff2');
const targetCssPath = path.join(root, 'public', 'assets', 'vendor', 'tabler-icons', 'tabler-icons.min.css');
const targetFontDir = path.join(root, 'public', 'assets', 'vendor', 'tabler-icons', 'fonts');
const targetFontPath = path.join(targetFontDir, 'tabler-icons.woff2');

const scanRoots = ['src', 'public', 'scripts'];
const scanExtensions = new Set(['.cjs', '.css', '.html', '.js', '.mjs']);
const ignoredSegments = new Set(['.git', 'dist', 'node_modules']);
const ignoredRelativePrefixes = [
  'public/assets/vendor/tabler-icons/',
  'scripts/vendor/'
];

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ignoredSegments.has(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);
    const relativePath = path.relative(root, fullPath).replace(/\\/g, '/');
    if (ignoredRelativePrefixes.some((prefix) => relativePath.startsWith(prefix))) continue;
    if (entry.isDirectory()) {
      walk(fullPath, files);
      continue;
    }
    if (entry.isFile() && scanExtensions.has(path.extname(entry.name))) files.push(fullPath);
  }
  return files;
}

function collectSourceFiles() {
  return scanRoots
    .map((dir) => path.join(root, dir))
    .filter((dir) => fs.existsSync(dir))
    .flatMap((dir) => walk(dir));
}

function parseIconCodepoints(css) {
  const map = new Map();
  const pattern = /\.ti-([a-z0-9-]+):before\{content:"\\([0-9a-fA-F]+)"\}/g;
  let match;
  while ((match = pattern.exec(css))) {
    map.set(`ti-${match[1]}`, match[2].toLowerCase());
  }
  return map;
}

function collectUsedIconClasses(files) {
  const used = new Set();
  const pattern = /\bti-[a-z0-9][a-z0-9-]*\b/g;
  for (const filePath of files) {
    const text = read(filePath);
    let match;
    while ((match = pattern.exec(text))) {
      used.add(match[0]);
    }
  }
  return Array.from(used).sort((left, right) => left.localeCompare(right));
}

function buildCss(icons, codepoints) {
  const rules = icons.map((icon) => `.${icon}:before{content:"\\${codepoints.get(icon)}"}`);
  return [
    '/*!',
    ' * Tabler Icons 3.40.0 by tabler - https://tabler.io',
    ' * License - https://github.com/tabler/tabler-icons/blob/master/LICENSE',
    ' * Subset generated by scripts/build/subset-tabler-icons.mjs',
    ' */',
    '@font-face{font-family:"tabler-icons";font-style:normal;font-weight:400;font-display:swap;src:url("./fonts/tabler-icons.woff2?v3.40.0-subset") format("woff2")}',
    '.ti{font-family:"tabler-icons" !important;speak:none;font-style:normal;font-weight:normal;font-variant:normal;text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}',
    ...rules
  ].join('');
}

function findPython() {
  const candidates = [
    process.env.PYTHON,
    'C:\\Users\\loru\\.cache\\codex-runtimes\\codex-primary-runtime\\dependencies\\python\\python.exe',
    'python',
    'py'
  ].filter(Boolean);
  return candidates.find((candidate) => {
    const result = spawnSync(candidate, ['-c', 'import fontTools.subset'], { stdio: 'ignore' });
    return result.status === 0;
  });
}

function subsetFont(unicodes) {
  const python = findPython();
  if (!python) {
    throw new Error('fontTools is required. Install with: python -m pip install fonttools brotli');
  }
  fs.mkdirSync(targetFontDir, { recursive: true });
  const result = spawnSync(python, [
    '-m',
    'fontTools.subset',
    sourceFontPath,
    `--unicodes=${unicodes}`,
    '--flavor=woff2',
    '--layout-features=*',
    '--symbol-cmap',
    '--legacy-cmap',
    '--notdef-glyph',
    '--notdef-outline',
    '--recommended-glyphs',
    '--name-IDs=*',
    '--name-legacy',
    '--name-languages=*',
    `--output-file=${targetFontPath}`
  ], { encoding: 'utf8' });
  if (result.status !== 0) {
    throw new Error(`fontTools subset failed:\n${result.stderr || result.stdout}`);
  }
}

function main() {
  const sourceCss = read(sourceCssPath);
  const codepoints = parseIconCodepoints(sourceCss);
  const usedIcons = collectUsedIconClasses(collectSourceFiles());
  const missing = usedIcons.filter((icon) => !codepoints.has(icon));
  if (missing.length) {
    throw new Error(`Missing Tabler icon codepoints: ${missing.join(', ')}`);
  }

  const unicodes = usedIcons
    .map((icon) => `U+${codepoints.get(icon).toUpperCase()}`)
    .join(',');
  fs.writeFileSync(targetCssPath, buildCss(usedIcons, codepoints), 'utf8');
  subsetFont(unicodes);

  for (const obsolete of ['tabler-icons.woff', 'tabler-icons.ttf']) {
    const obsoletePath = path.join(targetFontDir, obsolete);
    if (fs.existsSync(obsoletePath)) fs.rmSync(obsoletePath);
  }

  console.log(JSON.stringify({
    ok: true,
    icons: usedIcons.length,
    cssBytes: fs.statSync(targetCssPath).size,
    woff2Bytes: fs.statSync(targetFontPath).size
  }, null, 2));
}

main();
